"""
    extract_quadratic_map(TopoData::TopographicalData, N_1orN_2_offset::Int)

Extracts a square subsection of the cost map with a side length compatible with wavelet operations.

The dimensions are scaled to `2^n + offset`, where `n` is the largest power of two 
fitting within the original map boundaries.

# Arguments
- `TopoData::TopographicalData`: Input topographical data structure.
- `N_1orN_2_offset::Int`: Dimension offset mandated by the chosen wavelet boundary condition.

# Output
- `Tuple{TopographicalData, Int}`: A tuple containing the cropped quadratic map and the base exponent `n`.
"""
function extract_quadratic_map(TopoData::TopographicalData, N_1orN_2_offset::Int)
    size_mn = Int(floor(log2(minimum(size(TopoData.CostMap)))))
    new_size = 2^size_mn + N_1orN_2_offset
    
    new_map = TopoData.CostMap[1:new_size, 1:new_size]
    new_rTop = ind2coords((new_size, 1), TopoData)
    new_lBot = ind2coords((1, new_size), TopoData)
    
    return TopographicalData(new_map, (new_size, new_size), new_rTop, new_lBot, (1, 1)), size_mn
end




"""
    get_path(u::Int, start::Int, predecessor::AbstractVector)

Reconstructs the shortest path from the start node to the target node.

# Arguments
- `u::Int`: The target node index.
- `start::Int`: The source node index.
- `predecessor::AbstractVector`: The predecessor array generated by the shortest path algorithm.

# Output
- `Vector{Int}`: An ordered list of node indices representing the path from the target back to the start.
"""
function get_path(u::Int, start::Int, predecessor::AbstractVector)
    path = [u]
    while u != start 
        u  = Int(predecessor[u])
        push!(path, u)
    end
    return path
end


"""
    dijkstra_shortest_path(Ad::SparseMatrixCSC{<:Number}, start::Int; targets::Vector{Int}=Int[])

Calculates the shortest paths from a start node using an optimized Min-Heap Dijkstra algorithm.

# Arguments
- `Ad::SparseMatrixCSC{<:Number}`: Weighted adjacency matrix representing the graph.
- `start::Int`: Source node index.

# Keywords
- `targets::Vector{Int}`: Optional list of target nodes. If provided, the algorithm stops early once all targets are reached.

# Output
- `Tuple{Vector{Float64}, Vector{Int}}`: A tuple containing the travel costs to each node (`-1.0` if unreachable) and the predecessor list.
"""
function dijkstra_shortest_path(Ad::SparseMatrixCSC{<:Number}, start::Int; targets::Vector{Int}=Int[])
    n = size(Ad, 1)
    dist = fill(Inf, n)
    pred = zeros(Int, n)
    dist[start] = 0.0

    # Initialize custom MinHeap for O(E log V) performance
    heap = MinHeap(n)
    heap_push!(heap, start, 0.0)

    # Setup early stopping
    targets_left = length(targets)
    reached_targets = falses(n)

    while !heap_isempty(heap)
        u, current_dist = heap_pop!(heap)

        # Early stopping check
        if targets_left > 0 && !reached_targets[u] && (u in targets)
            reached_targets[u] = true
            targets_left -= 1
            if targets_left == 0
                break # All target nodes found!
            end
        end

        # Fast traversal of sparse matrix columns
        for idx in Ad.colptr[u]:(Ad.colptr[u+1]-1)
            v = Ad.rowval[idx]
            weight = Ad.nzval[idx]

            if weight > 0
                alt = current_dist + weight
                if alt < dist[v]
                    dist[v] = alt
                    pred[v] = u
                    
                    # Update or push to heap
                    if heap_contains(heap, v)
                        heap_decrease_key!(heap, v, alt)
                    else
                        heap_push!(heap, v, alt)
                    end
                end
            end
        end
    end

    # Format output for backwards compatibility (unreachable = -1.0)
    allocated_list = copy(dist)
    allocated_list[isinf.(allocated_list)] .= -1.0

    return allocated_list, pred
end

"""
    compress(Topdata::AbstractLCPAData, k::Int, l::Int)

Compresses a cost raster matrix by averaging blocks of `k × l` cells into single cells.

# Arguments
- `Topdata::AbstractLCPAData`: Topographical data structure containing the `CostMap` to be compressed.
- `k::Int`: Number of rows to aggregate per block.
- `l::Int`: Number of columns to aggregate per block.

# Output
- `TopographicalData`: A new data structure containing the compressed matrix.
"""
function compress(Topdata::AbstractLCPAData, k::Int, l::Int) 
    if k==1 && l == 1 return Topdata end 
    @info "Compressing starts..."
    m, n = Topdata.size

    comp = zeros(ceil(Int,m/k), ceil(Int, n/l))

    @showprogress for i in 1:ceil(Int,m/k)
        for j in 1:ceil(Int, n/l)
            r_start = (i-1)*k+1
            r_end   = min(i*k, m)
            c_start = (j-1)*l+1
            c_end   = min(j*l, n)
            block = @view Topdata.CostMap[r_start:r_end, c_start:c_end]
            comp[i,j] = sum(block) / length(block)
        end
    end
    @info "Compressing is done and of size $(size(comp))"
    return TopographicalData(comp, Topdata.size, Topdata.lBot, Topdata.rTop, (k,l))
end

"""
    all_pairs_LCPA(TopData::TopographicalData, Ad::AbstractMatrix, sites::AbstractVector)

Calculates the least cost paths between all provided coordinate sites and plots the results.

# Arguments
- `TopData::TopographicalData`: Topographical data structure.
- `Ad::AbstractMatrix`: The adjacency matrix representing the graph.
- `sites::AbstractVector`: A list of target site coordinates `(latitude, longitude)`.

# Output
- `nothing`: The function generates and displays a `Plots.jl` visualization.
"""
function all_pairs_LCPA(TopData::TopographicalData, Ad::AbstractMatrix, sites::AbstractVector)
    start_lexi_list = [coords2lexi(sites[i], TopData) for i in eachindex(sites)]

    p1 = plot(xlims=(TopData.lBot[1], TopData.rTop[1]), ylims=(TopData.lBot[2], TopData.rTop[2]), legend=:outertopright)
    for i in eachindex(sites)
        scatter!(p1, sites[i], label="$(sites[i])")
    end

    for i in start_lexi_list
        _, pred = dijkstra_shortest_path(Ad, i, targets=start_lexi_list)
        for j in start_lexi_list
            if j != i
                path = get_path(j, i, pred)
                path_coords = ind2coords.(lexi2ind.(path, [TopData]), [TopData])
                plot!(p1, path_coords, label="$(path_coords[end])")
            end
        end
    end
    display(p1)
end


"""
    all_pairs_LCPA_GMT(TopData::TopographicalData, Ad::AbstractMatrix, sites::AbstractVector{Tuple{Real, Real}}; output_dir::String = pwd())

Calculates the least cost paths between all provided sites and plots the results using GMT.jl.

# Arguments
- `TopData::TopographicalData`: Topographical data structure.
- `Ad::AbstractMatrix`: The adjacency matrix representing the graph.
- `sites::AbstractVector{Tuple{Real, Real}}`: A list of site coordinates.

# Keywords
- `output_dir::String`: Directory to save the resulting map image (default: current working directory).

# Output
- `nothing`: Generates a high-quality GMT plot and saves it to disk.
"""
function all_pairs_LCPA_GMT(TopData::TopographicalData, Ad::AbstractMatrix, sites::AbstractVector{Tuple{Real, Real}}; output_dir::String = pwd(), overwrite::Bool = false)
    start_lexi_list = [coords2lexi(sites[i], TopData) for i in eachindex(sites)]

    left_border, right_border = extrema([s[1] for s in sites])
    bottom_border, top_border = extrema([s[2] for s in sites])

    Δlong = 3; Δlat=3
    reg = "$(left_border-Δlong)/$(bottom_border-Δlat)/$(right_border+2*Δlong)/$(top_border+Δlat)+r"
    GMT.grdimage("@earth_relief_01m", region=reg, proj=:M15c, cmap=:geo)
    GMT.coast!(shorelines=:thin, borders=1, frame=:ag, area=500)

    for (i_ind, i) in enumerate(start_lexi_list)
        _, pred = dijkstra_shortest_path(Ad, i)
        for (j_ind, j) in enumerate(start_lexi_list)
            if j != i
                path = get_path(j, i, pred)
                path_coords = ind2coords.(lexi2ind.(path, [TopData]), [TopData])
                
                for (k, coords) in enumerate(path_coords[1:end-1]) 
                    GMT.lines!([path_coords[k][1] path_coords[k][2]; path_coords[k+1][1] path_coords[k+1][2]], pen=(1.5,:white))
                end
            end
        end
    end

    if output_dir != pwd()
        if isdir(output_dir)
            if overwrite == false
                error("Folder '$output_dir' already exists! To overwrite files, use the argument `overwrite=true`.")
            else
                @info "Folder already exists. Files will be overwritten (overwrite=true)."
            end
        else
            mkpath(output_dir)
        end
    end

    figname_path = joinpath(output_dir, "$(TopData.kl)_Stereographic")
    
    GMT.scatter!(
            float.([sites[i][1] for i in eachindex(sites)]), float.([sites[i][2] for i in eachindex(sites)]),
            fmt=:png, 
            marker=:circle,
            markeredgecolor=0, 
            size=0.2, 
            markerfacecolor=:blue, 
            show=true,
            figname=figname_path
    )
end


"""
    all_pairs_LCPA_adaptive(TopData::TopographicalData, Ad_leaves::AbstractMatrix, leaves::Vector{Tuple{Int,Int,Int}}, L_geom::Int, sites::AbstractVector)

Performs a least cost path analysis between multiple sites on an adaptively refined quadtree graph.

# Arguments
- `TopData::TopographicalData`: Topographical data structure.
- `Ad_leaves::AbstractMatrix`: The adaptive adjacency matrix.
- `leaves::Vector{Tuple{Int,Int,Int}}`: Vector of adaptive quadtree leaf cells.
- `L_geom::Int`: The finest geometric level of the quadtree decomposition.
- `sites::AbstractVector`: A list of geographic coordinates.

# Output
- `nothing`: Generates and displays a `Plots.jl` visualization.
"""
function all_pairs_LCPA_adaptive(TopData::TopographicalData, Ad_leaves::AbstractMatrix, leaves::Vector{Tuple{Int,Int,Int}}, L_geom::Int, sites::AbstractVector)
    # 1. Sites auf die adaptiven Knoten-Indizes mappen
    start_leaf_list = [coords2leaf_index(sites[i], leaves, TopData, L_geom) for i in eachindex(sites)]

    p1 = plot(xlims=(TopData.lBot[1], TopData.rTop[1]), ylims=(TopData.lBot[2], TopData.rTop[2]), legend=:outertopright)
    for i in eachindex(sites)
        scatter!(p1, sites[i], label="$(sites[i])")
    end

    # 2. Regulären Dijkstra auf dem adaptiven Graphen laufen lassen
    for i in start_leaf_list
        _, pred = dijkstra_shortest_path(Ad_leaves, i, targets=start_leaf_list)
        
        for j in start_leaf_list
            if j != i
                path_indices = get_path(j, i, pred)
                
                # 3. Pfad-Indizes (Knoten) zurück in physikalische Koordinaten wandeln
                # Wir greifen auf die Leaves-Tupel zu und nutzen dein bestehendes ind2coords
                path_coords = [ind2coords(leaves[idx], TopData, L_geom) for idx in path_indices]
                
                plot!(p1, path_coords, label="Path", lw=2)
            end
        end
    end
    display(p1)
end



######################################################################
# 1. DATA STRUCTURES: Min-Heap for Optimized Dijkstra
######################################################################

"""
    MinHeap

A lightweight, custom binary min-heap structure optimized for Dijkstra's algorithm.

It maintains an internal position array (`pos`) to allow for `O(log V)` key decrease operations, 
which is crucial for fast shortest-path calculations on large graphs.
"""
mutable struct MinHeap
    keys::Vector{Float64}      # cost values
    nodes::Vector{Int}         # node ids
    pos::Vector{Int}           # pos[node] → index in keys/nodes (0 = not in heap)
    n::Int                     # current number of elements
end

"""
    MinHeap(capacity::Int)

Initializes an empty `MinHeap` with the specified maximum capacity.
"""
function MinHeap(capacity::Int)
    return MinHeap(Vector{Float64}(undef, capacity),
                   Vector{Int}(undef, capacity),
                   zeros(Int, capacity), 0)
end

@inline function _swap!(h::MinHeap, i::Int, j::Int)
    h.keys[i], h.keys[j] = h.keys[j], h.keys[i]
    h.nodes[i], h.nodes[j] = h.nodes[j], h.nodes[i]
    h.pos[h.nodes[i]] = i
    h.pos[h.nodes[j]] = j
end

function _siftup!(h::MinHeap, i::Int)
    while i > 1
        p = i >> 1
        h.keys[i] < h.keys[p] || break
        _swap!(h, i, p)
        i = p
    end
end

function _siftdown!(h::MinHeap, i::Int)
    @inbounds while true
        smallest = i
        l = 2i; r = 2i + 1
        if l <= h.n && h.keys[l] < h.keys[smallest]; smallest = l; end
        if r <= h.n && h.keys[r] < h.keys[smallest]; smallest = r; end
        smallest == i && break
        _swap!(h, i, smallest)
        i = smallest
    end
end

function heap_push!(h::MinHeap, node::Int, key::Float64)
    h.n += 1
    h.keys[h.n] = key
    h.nodes[h.n] = node
    h.pos[node] = h.n
    _siftup!(h, h.n)
end

function heap_pop!(h::MinHeap)
    node = h.nodes[1]; key = h.keys[1]
    h.pos[node] = 0
    if h.n > 1
        h.keys[1] = h.keys[h.n]
        h.nodes[1] = h.nodes[h.n]
        h.pos[h.nodes[1]] = 1
    end
    h.n -= 1
    h.n > 0 && _siftdown!(h, 1)
    return node, key
end

function heap_decrease_key!(h::MinHeap, node::Int, newkey::Float64)
    i = h.pos[node]
    h.keys[i] = newkey
    _siftup!(h, i)
end

@inline heap_contains(h::MinHeap, node::Int) = h.pos[node] != 0
@inline heap_isempty(h::MinHeap) = h.n == 0


"""
    delConnections(Ad::AbstractMatrix, keepNodes::AbstractVector{Bool})

Removes unwanted connections from an adjacency matrix based on a boolean mask.

# Arguments
- `Ad::AbstractMatrix`: The original adjacency matrix representing the graph.
- `keepNodes::AbstractVector{Bool}`: A boolean vector where `true` indicates a node (and its connections) should be kept.

# Output
- `SparseMatrixCSC`: A new adjacency matrix with the specified nodes entirely isolated/removed.
"""
function delConnections(Ad::AbstractMatrix, keepNodes::AbstractVector{Bool})
    A = spdiagm(keepNodes)
    newAd = A * Ad * A
    return dropzeros(newAd)
end

"""
    neighbours(u::Int, Ad::SparseMatrixCSC{<:Number})

Retrieves the neighbouring nodes for a given node `u`.

Neighbours are defined as all cells with strictly positive values in the `u`-th column 
of the adjacency matrix.

# Arguments
- `u::Int`: The node index.
- `Ad::AbstractArray{<:Number}`: The adjacency matrix of the graph.

# Output
- `Vector{Int}`: A vector containing the indices of all adjacent nodes.
"""
function neighbours(u::Int, Ad::AbstractArray{<:Number})
    return findall(>(0), @view(Ad[:, u]))
end

